//! レビュー面（内蔵`ReviewPanel`）の手動E2E用フィクスチャ生成器。
//!
//! ```text
//! cargo run -p harness-cli --example review-e2e-fixtures -- <出力ディレクトリ>
//! ```
//!
//! **なぜ実装コード経由で作るのか**: ステージ済み変更の実体は「オーバーレイのファイル＋
//! 操作台帳（`.harness-cow-ops.jsonl`）＋baselineミラー」の3点セットで、台帳の`baseline_hash`は
//! `harness_change_ledger::hash_bytes`（Rustの`DefaultHasher`）でなければならない。手書きや
//! 外部スクリプトで作ると必ずずれ、`apply`が全件conflictになる。ここでは実際の
//! `SandboxFs::write_string`/`remove`を呼ぶので、製品が書くものとバイト単位で同じになる。
//!
//! 生成物:
//!
//! - `<out>/cow/` — 8シナリオ分のワークスペース。各シナリオが1セッション
//!   （`.harness/sessions/session-<id>.jsonl`）＋1オーバーレイ（`.harness/sandbox/session-<id>/`）
//!   を持ち、`harness --staged --resume <id>`で開くとその変更だけがレビュー対象になる。
//! - `%APPDATA%\harness\data\memory\<workspace-key>\` — Recall記憶のレビュー用データ4種
//!   （`plans/PLAN-RECALL-MEMORY.md`）。**`RecallStore`経由で作る**ので、
//!   `harness memory list --all`・TUIの`/memory`からそのまま見える。

use std::path::{Path, PathBuf};

use harness_cognition::{Checkpoint, CheckpointMeta, RecallStore, ReviewedWatermark};
use harness_core::{ContentBlock, Message, Role, StagingConfig, StagingMode};
use harness_engine::SessionStore;
use harness_sandbox::SandboxFs;

/// 生成物であることの目印。既存ディレクトリを消す前にこれを確認する。
const MARKER: &str = "REVIEW-E2E-FIXTURES.md";

fn main() {
    let mut args = std::env::args().skip(1);
    let Some(out) = args.next() else {
        eprintln!("usage: cargo run -p harness-cli --example review-e2e-fixtures -- <out-dir>");
        std::process::exit(2);
    };
    let out = PathBuf::from(out);
    prepare_root(&out);

    let cow_ws = out.join("cow");
    std::fs::create_dir_all(cow_ws.join(".harness").join("sessions")).unwrap();
    build_cow_scenarios(&cow_ws);

    let recall_roots = build_recall_fixtures(&out);
    let combo = build_combo(&out);

    write_readme(&out, &cow_ws, &recall_roots, combo.as_ref());
    println!("\n生成しました: {}", out.display());
    println!("次に読むもの: {}", out.join(MARKER).display());
}

/// 出力先を空にする。**目印ファイルが無い既存ディレクトリは消さない**（生成器に他人の
/// ディレクトリを消させない）。
fn prepare_root(out: &Path) {
    if out.exists() {
        if !out.join(MARKER).exists() {
            eprintln!(
                "refusing to overwrite {}: it exists and has no {MARKER} marker",
                out.display()
            );
            std::process::exit(2);
        }
        std::fs::remove_dir_all(out).expect("remove previous fixtures");
    }
    std::fs::create_dir_all(out).expect("create out dir");
    std::fs::write(out.join(MARKER), "generated by review-e2e-fixtures\n").unwrap();
}

// ---------------------------------------------------------------- CoW/staged

struct Scenario {
    /// `--resume <id>`に渡す識別子（セッションファイル名は`session-<id>.jsonl`）。
    id: &'static str,
    /// `/sessions`一覧に出る1行目（最初のユーザー発話）。
    headline: String,
    /// パネルで何を見るか（READMEに出す）。
    expect: &'static str,
    /// 会話（セッションファイルへ書く）。
    conversation: Vec<Message>,
    /// **生成後に実際の`review_file`で数えた**エントリ内訳。手書きの期待値ではなく、
    /// パネルが本当に出すものを一覧へ書き出すため。
    files: Vec<FileFacts>,
}

struct FileFacts {
    path: String,
    op: String,
    hunks: usize,
    block: Option<String>,
}

fn build_cow_scenarios(ws: &Path) {
    let scenarios = [
        multi_short(ws),
        multi_long(ws),
        single_modify_short(ws),
        single_modify_long(ws),
        single_create_short(ws),
        single_create_long(ws),
        single_delete_short(ws),
        single_delete_long(ws),
    ];
    let sessions_dir = ws.join(".harness").join("sessions");
    for s in &scenarios {
        let store = SessionStore::open(sessions_dir.join(format!("session-{}.jsonl", s.id)));
        store.append_messages(&s.conversation).unwrap();
        println!("[cow] session-{:<22} {}", s.id, s.expect);
    }
    std::fs::write(ws.join("SCENARIOS.md"), scenario_table(&scenarios)).unwrap();
}

fn scenario_table(scenarios: &[Scenario]) -> String {
    let mut out = String::from(
        "# CoW/stagedシナリオ一覧\n\n\
         各シナリオは`harness.exe --staged --resume <id>`で開く（レビュー対象は**起動時の\n\
         セッション**で決まる。TUI内の`/sessions`では会話だけが切り替わり、レビュー対象は\n\
         切り替わらない）。\n\n\
         | `--resume` | 会話 | 件数 | 見どころ |\n|---|---|---|---|\n",
    );
    for s in scenarios {
        out.push_str(&format!(
            "| `{}` | {}件・{} | {} | {} |\n",
            s.id,
            s.conversation.len(),
            if s.conversation.len() > 4 { "長文" } else { "短文" },
            s.files.len(),
            s.expect
        ));
    }
    out.push_str("\n## エントリ内訳（`review_file`の実測値）\n\n");
    for s in scenarios {
        out.push_str(&format!("### `{}`\n\n> {}\n\n", s.id, s.headline));
        out.push_str("| パス | 操作 | ハンク数 | ハンク操作 |\n|---|---|---|---|\n");
        for f in &s.files {
            out.push_str(&format!(
                "| `{}` | {} | {} | {} |\n",
                f.path,
                f.op,
                f.hunks,
                match &f.block {
                    None => "可".to_string(),
                    Some(reason) => format!("不可（{reason}）"),
                }
            ));
        }
        out.push('\n');
    }
    out
}

/// 1シナリオ分のオーバーレイを作る。`seed`が実workspace側の元の姿、`edit`がエージェントの
/// 書込み（オーバーレイ＋台帳＋baselineミラーがここで実際に作られる）。
///
/// 戻り値は**製品コード（`review_file`）が実際に計算した**内訳。一覧に手書きの期待値を
/// 載せると、生成物と食い違ったときにE2Eの時間を無駄にするため、事実だけを書き出す。
fn staged_overlay(
    ws: &Path,
    id: &str,
    seed: impl Fn(&Path),
    edit: impl Fn(&SandboxFs),
) -> Vec<FileFacts> {
    seed(ws);
    let staging = StagingConfig {
        mode: StagingMode::Staged,
        sandbox_dir: Some(
            PathBuf::from(".harness")
                .join("sandbox")
                .join(format!("session-{id}")),
        ),
    };
    let fs = SandboxFs::open(ws, &staging).expect("open sandbox");
    edit(&fs);
    fs.change_set()
        .expect("change set")
        .iter()
        .map(|entry| {
            let review = fs.review_file(entry);
            FileFacts {
                path: entry.path.clone(),
                op: format!("{:?}", entry.op),
                hunks: review.hunks.len(),
                block: review.hunk_block.map(|b| b.reason().to_string()),
            }
        })
        .collect()
}

fn write_file(ws: &Path, rel: &str, content: &str) {
    let path = ws.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, content).unwrap();
}

fn write_bytes(ws: &Path, rel: &str, content: &[u8]) {
    let path = ws.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, content).unwrap();
}

