fn multi_short(ws: &Path) -> Scenario {
    let id = "multi-short";
    let files = staged_overlay(
        ws,
        id,
        |ws| {
            write_file(ws, "multi-short/src/app.ts", &short_ts("app entry"));
            write_file(ws, "multi-short/config.json", "{\n  \"name\": \"demo\",\n  \"retries\": 3\n}\n");
            write_file(ws, "multi-short/notes/todo.md", "- [ ] 古いTODO\n- [ ] もう使っていない\n");
        },
        |fs| {
            // 離れた2箇所を変える（＝ハンク2つ）。
            let modified = short_ts("app entry")
                .replace("const name = \"world\";", "const name = \"harness\";")
                .replace("export const RETRIES = 3;", "export const RETRIES = 5;");
            fs.write_string("multi-short/src/app.ts", &modified).unwrap();
            fs.write_string(
                "multi-short/config.json",
                "{\n  \"name\": \"demo\",\n  \"retries\": 5\n}\n",
            )
            .unwrap();
            fs.write_string(
                "multi-short/src/util.ts",
                "export function clamp(v: number, lo: number, hi: number) {\n  return Math.min(hi, Math.max(lo, v));\n}\n",
            )
            .unwrap();
            fs.remove("multi-short/notes/todo.md").unwrap();
        },
    );
    Scenario {
        id,
        files,
        headline: "リトライ回数を5に上げて、使っていないTODOを消して".to_string(),
        expect: "4件（M 2件・A 1件・D 1件）。`app.ts`が2ハンク、他は1ハンク/全体",
        conversation: short_conversation(
            "リトライ回数を5に上げて、使っていないTODOを消して",
            "app.ts・config.jsonを変更し、util.tsを追加、notes/todo.mdを削除しました。",
        ),
    }
}

fn multi_long(ws: &Path) -> Scenario {
    let id = "multi-long";
    let files = staged_overlay(
        ws,
        id,
        |ws| {
            write_file(ws, "multi-long/src/engine.rs", &long_rs(320));
            write_file(ws, "multi-long/docs/guide.md", &long_ja_doc(14));
            write_file(ws, "multi-long/legacy/old_module.rs", &long_rs(120));
            // CRLFのファイル（部分適用で改行が壊れないことを目で見る）。
            write_file(
                ws,
                "multi-long/data/win.txt",
                &long_rs(60).replace('\n', "\r\n"),
            );
            // 非UTF-8（「preview only」の注記が出る）。
            write_bytes(
                ws,
                "multi-long/assets/blob.bin",
                &[0x00, 0xff, 0xfe, b'b', b'i', b'n', 0x80, b'\n'],
            );
        },
        |fs| {
            let long = long_rs(320);
            let modified = long
                .replace("pub fn step_1(", "pub fn step_1_renamed(")
                .replace("pub fn step_97(", "pub fn step_97_renamed(")
                .replace("pub fn step_193(", "pub fn step_193_renamed(")
                .replace("pub fn step_301(", "pub fn step_301_renamed(");
            fs.write_string("multi-long/src/engine.rs", &modified).unwrap();

            let doc = long_ja_doc(14)
                .replace("## 0. 節タイトル0", "## 0. 節タイトル0（改訂）")
                .replace("## 7. 節タイトル7", "## 7. 節タイトル7（改訂）")
                .replace("## 13. 節タイトル13", "## 13. 節タイトル13（改訂）");
            fs.write_string("multi-long/docs/guide.md", &doc).unwrap();

            fs.write_string("multi-long/src/generated_report.md", &long_ja_doc(10))
                .unwrap();
            fs.remove("multi-long/legacy/old_module.rs").unwrap();

            let crlf = long_rs(60)
                .replace("pub fn step_1(", "pub fn step_1_renamed(")
                .replace("pub fn step_49(", "pub fn step_49_renamed(")
                .replace('\n', "\r\n");
            fs.write_string("multi-long/data/win.txt", &crlf).unwrap();

            fs.write_string("multi-long/assets/blob.bin", "テキストで上書きした\n")
                .unwrap();
        },
    );
    Scenario {
        id,
        files,
        headline: "エンジンとガイドを一括で改訂して、旧モジュールを撤去して".to_string(),
        expect: "6件（M 4件・A 1件・D 1件）。`engine.rs`は4ハンク、`win.txt`はCRLF、`blob.bin`は非UTF-8で降格",
        conversation: long_conversation(
            "エンジンとガイドを一括で改訂して、旧モジュールを撤去して",
            "`multi-long/`配下を対象に、engine.rs・guide.md・win.txtを改訂します。",
        ),
    }
}

