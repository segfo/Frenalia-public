/// **CoWの未適用変更とRecallの未レビュー記憶が同時に存在する**ワークスペース。
/// 記憶はワークスペース単位（セッション単位ではない）なので、2つのセッションが同じ記憶
/// ディレクトリを共有する——「どのセッションで開いても未レビュー記憶は同じ」という
/// 設計どおりの見え方をそのまま再現している。
fn build_combo(out: &Path) -> Option<ComboFixture> {
    let ws = out.join("combo");
    std::fs::create_dir_all(ws.join(".harness").join("sessions")).unwrap();

    let scenarios = [combo_short(&ws), combo_long(&ws)];
    let sessions_dir = ws.join(".harness").join("sessions");
    for s in &scenarios {
        let store = SessionStore::open(sessions_dir.join(format!("session-{}.jsonl", s.id)));
        store.append_messages(&s.conversation).unwrap();
        println!("[combo] session-{:<22} {}", s.id, s.expect);
    }
    std::fs::write(ws.join("SCENARIOS.md"), scenario_table(&scenarios)).unwrap();

    // 8件のうち先頭3件をレビュー済みにする（ウォーターマークを添字2へ進める）＝
    // 残り5件（短文2・長文3）が未レビュー。
    let specs: Vec<CheckpointSpec> = (0..8).map(|i| CheckpointSpec::new(i, i >= 5)).collect();
    let dir = write_memory(&ws, &specs, Some(2))?;
    println!("[combo] memory -> {} (8件中5件が未レビュー)", dir.display());
    Some(ComboFixture {
        workspace: ws,
        memory: dir,
    })
}

