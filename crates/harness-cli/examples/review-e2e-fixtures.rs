fn short_ts(title: &str) -> String {
    format!(
        "// {title}\n\
         export function main() {{\n\
         \x20 const name = \"world\";\n\
         \x20 console.log(`hello ${{name}}`);\n\
         }}\n\
         \n\
         export function add(a: number, b: number) {{\n\
         \x20 return a + b;\n\
         }}\n\
         \n\
         export function sub(a: number, b: number) {{\n\
         \x20 return a - b;\n\
         }}\n\
         \n\
         export const VERSION = \"0.1.0\";\n\
         export const DEBUG = false;\n\
         export const RETRIES = 3;\n\
         export const TIMEOUT_MS = 1000;\n"
    )
}

/// `lines`行の疑似Rustソース。行番号を埋め込んであるので、どのハンクを見ているかが分かる。
fn long_rs(lines: usize) -> String {
    let mut out = String::from("//! 長文シナリオ用の疑似モジュール（自動生成）。\n\nuse std::collections::HashMap;\n\n");
    for i in 0..lines {
        match i % 12 {
            0 => out.push_str(&format!("/// 手続き{i}の説明。ここは変更されない文脈行です。\n")),
            1 => out.push_str(&format!("pub fn step_{i}(input: &str) -> String {{\n")),
            2 => out.push_str(&format!("    let mut buf = String::with_capacity({});\n", i * 8)),
            3 => out.push_str("    for (idx, ch) in input.char_indices() {\n"),
            4 => out.push_str("        if idx % 2 == 0 {\n"),
            5 => out.push_str("            buf.push(ch.to_ascii_uppercase());\n"),
            6 => out.push_str("        } else {\n"),
            7 => out.push_str("            buf.push(ch);\n"),
            8 => out.push_str("        }\n"),
            9 => out.push_str("    }\n"),
            10 => out.push_str("    buf\n"),
            _ => out.push_str("}\n\n"),
        }
    }
    out
}

/// 日本語の長文ドキュメント。**折り返し無しのdiffペインで右端が切れる長い行**を混ぜてある。
fn long_ja_doc(sections: usize) -> String {
    let mut out = String::from("# 運用ガイド（自動生成の長文サンプル）\n\n");
    for i in 0..sections {
        out.push_str(&format!("## {i}. 節タイトル{i}\n\n"));
        out.push_str(&format!(
            "この節は自動生成された説明文です（節番号{i}）。レビューパネルの表示確認のために、\n\
             短い行と長い行を混在させています。\n"
        ));
        out.push_str(&format!(
            "長い行の例（{i}）: {}\n\n",
            "この行はdiffペインの右端で切れることを確認するための非常に長い一行です。".repeat(4)
        ));
    }
    out
}

fn tool_call(id: &str, name: &str, input: serde_json::Value, output: &str) -> Vec<Message> {
    vec![
        Message {
            role: Role::Assistant,
            content: vec![ContentBlock::ToolUse {
                id: id.to_string(),
                name: name.to_string(),
                input,
            }],
        },
        Message {
            role: Role::User,
            content: vec![ContentBlock::ToolResult {
                tool_use_id: id.to_string(),
                content: output.to_string(),
                is_error: false,
            }],
        },
    ]
}

fn user(text: &str) -> Message {
    Message {
        role: Role::User,
        content: vec![ContentBlock::Text(text.to_string())],
    }
}

fn assistant(text: &str) -> Message {
    Message {
        role: Role::Assistant,
        content: vec![ContentBlock::Text(text.to_string())],
    }
}

/// 長い会話（transcriptのスクロール・折り畳みも一緒に見るため）。
fn long_conversation(topic: &str, extra: &str) -> Vec<Message> {
    let mut msgs = vec![
        user(&format!(
            "{topic}。長文シナリオなので、変更の意図と影響範囲を詳しく説明しながら進めてください。"
        )),
        assistant(&format!(
            "承知しました。まず対象を把握します。{extra}\n\n\
             このセッションは**レビューパネルの手動E2E用に生成された会話データ**で、実際のモデル\n\
             呼び出しは行われていません。以下の説明はパネルの見え方（長い本文・折り畳み・\n\
             スクロール）を確認するための埋め草です。\n\n\
             {}",
            "処理の各段階について、入力・出力・失敗時の挙動を順に述べます。".repeat(6)
        )),
    ];
    msgs.extend(tool_call(
        "call_glob_1",
        "glob",
        serde_json::json!({ "pattern": "**/*.rs" }),
        "matched 3 files",
    ));
    msgs.push(assistant(&format!(
        "対象が分かったので編集します。\n\n{}",
        "変更点は互いに離れた位置にあるため、レビューでは複数のハンクとして表示されるはずです。"
            .repeat(5)
    )));
    msgs.extend(tool_call(
        "call_edit_1",
        "edit_file",
        serde_json::json!({
            "path": "example.rs",
            "old_string": "let mut buf = String::new();",
            "new_string": "let mut buf = String::with_capacity(64);"
        }),
        "edited",
    ));
    msgs.push(assistant(
        "編集が終わりました。`/fsstage commit`（またはスラッシュコマンド）でパネルを開き、\n\
         ハンク単位で採否を決めてください。",
    ));
    msgs
}

fn short_conversation(topic: &str, done: &str) -> Vec<Message> {
    vec![
        user(topic),
        assistant(done),
        user("ではレビューします。"),
        assistant("`/fsstage commit`でパネルを開けます。"),
    ]
}

